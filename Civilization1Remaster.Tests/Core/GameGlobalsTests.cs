		[Fact]
		public void GroupsHoldEveryVariableOnce()
		{
			ushort[] addresses = new GameGlobals().All.Select(word => word.Address).ToArray();

			Assert.Equal(209, addresses.Length);
			Assert.Equal(addresses.Length, addresses.Distinct().Count());
			Assert.Equal(OriginalAddresses.Order(), addresses.Order());
		}

		[Fact]
		public void GroupPropertiesReadAndWriteTheirWord()
		{
			GameGlobals globals = new GameGlobals();
			globals.CityTurn.Food = 0x1234;
			globals.Scoring.VerticalShift = -3;
			globals.Menu.DisabledLines = 0xabcd;
			globals.Menu.DisabledLinesLow = 0x12;

			GlobalWord food = globals.All.Single(word => word.Address == 0x70da);
			GlobalWord shift = globals.All.Single(word => word.Address == 0x5116);

			Assert.Equal(0x1234, food.Value);
			Assert.Equal(0xfffd, shift.Value);
			Assert.Equal(0xab12, globals.Menu.DisabledLines);
			Assert.Equal(0x6822, globals.Files.SavedHumanPlayerAddress);
		}
