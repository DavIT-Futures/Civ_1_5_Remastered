"""
Copies the original code of rewritten functions verbatim from git into the reference (oracle) classes of the
differential tests, one file per function: Reference/<Class>Reference.<Method>.cs.

Calls of other methods of the same class are redirected to the current game code (this.owner.<Property>.Method(...)),
so a differential test checks exactly one function.

usage (from the repository root):
  python Civilization1Remaster.Tests/Differential/Reference/extract_reference.py <commit> <source file> <engine property> <method>...
example:
  python ... 17b9d32 Civilization1Remaster.Core/Game/UnitManagement.cs UnitOps ShiftUnit
<commit> is the last commit with the original code (the one before the rewrite).
"""
import os
import re
import subprocess
import sys

commit, source, prop = sys.argv[1:4]
methods = sys.argv[4:]

text = subprocess.run(['git', 'show', f'{commit}:{source}'], capture_output=True, check=True,
                      encoding='utf-8').stdout.replace('\r\n', '\n').split('\n')
original_class = os.path.splitext(os.path.basename(source))[0]
reference_class = original_class + 'Reference'
declared = set(re.findall(r'^\t\t(?:public|private|internal)[^=(]*?\s(\w+)\(', '\n'.join(text), re.M))

for method in methods:
    start = next(i for i, line in enumerate(text) if re.match(rf'^\t\t(public|private|internal) .*\s{method}\(', line))
    while text[start - 1].strip().startswith('///'):
        start -= 1
    end = next(i for i in range(start, len(text)) if text[i] == '\t\t}')
    body = '\n'.join(text[start:end + 1])

    for name in declared - {method}:
        body = re.sub(rf'(?<![\w.]){name}\(', f'this.owner.{prop}.{name}(', body)

    out = os.path.join(os.path.dirname(__file__), f'{reference_class}.{method}.cs')
    usings = sorted(set(['using System;', 'using Civilization1Remaster.Emulation;', 'using Civilization1Remaster.Game;',
                         'using Civilization1Remaster.Game.Rules;', 'using Civilization1Remaster.Game.State;',
                         'using Civilization1Remaster.Video;'] +
                        [line.strip() for line in text if line.startswith('using ') and line.strip().endswith(';')] +
                        ['using ' + line.split()[1].rstrip(';') + ';' for line in text if line.startswith('namespace ')]))
    usings_text = '\n'.join(usings)
    content = f'''// Generated by extract_reference.py from {source} at commit {commit}, do not edit
{usings_text}

namespace Civilization1Remaster.Tests.Differential.Reference
{{
	public sealed partial class {reference_class}
	{{
{body}
	}}
}}
'''
    with open(out, 'w', encoding='utf-8', newline='\r\n') as stream:
        stream.write(content)
    print('written', out)
